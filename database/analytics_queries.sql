    RAW_DATA:customer_id::VARCHAR AS CUSTOMER_ID,
    RAW_DATA:customer_name::VARCHAR AS CUSTOMER_NAME,
    RAW_DATA:customer_type::VARCHAR AS CUSTOMER_TYPE,
    RAW_DATA:city::VARCHAR AS CITY,
    RAW_DATA:preferred_fuel::VARCHAR AS PREFERRED_FUEL,
    LOADED_AT
FROM CUSTOMER_DATA.CUSTOMER_JSON_DATA;

