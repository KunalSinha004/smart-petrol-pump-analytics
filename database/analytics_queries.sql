USE WAREHOUSE SPPA_WH;
USE DATABASE SMART_PETROL_DB;

-- 1. Executive Summary Daily Run
SELECT 
    COUNT(DISTINCT s.SALE_ID) AS TOTAL_TRANSACTIONS,
    COALESCE(SUM(s.SALES_AMOUNT), 0) AS TOTAL_REVENUE,
    COALESCE(SUM(s.QUANTITY_LITRES), 0) AS TOTAL_LITRES_SOLD,
    COALESCE(SUM(s.GROSS_PROFIT), 0) AS TOTAL_GROSS_PROFIT,
    COALESCE(AVG(s.SALES_AMOUNT), 0) AS AVG_TRANSACTION_VALUE
FROM SALES_MANAGEMENT.FUEL_SALES s;

-- 2. Daily Sales Trend with 7-Day Moving Average (Window Function)
WITH DAILY_METRICS AS (
    SELECT 
        SALE_DATE,
        SUM(SALES_AMOUNT) AS DAILY_REVENUE,
        SUM(QUANTITY_LITRES) AS DAILY_VOLUME,
        COUNT(SALE_ID) AS DAILY_TXNS
    FROM SALES_MANAGEMENT.FUEL_SALES
    GROUP BY SALE_DATE
)
SELECT 
    SALE_DATE,
    DAILY_REVENUE,
    DAILY_VOLUME,
    DAILY_TXNS,
    AVG(DAILY_REVENUE) OVER (
        ORDER BY SALE_DATE 
        ROWS BETWEEN 6 PRECEDING AND CURRENT ROW
    ) AS SEVEN_DAY_MOVING_AVG_REVENUE
FROM DAILY_METRICS
ORDER BY SALE_DATE ASC;

-- 3. Fuel Type Breakdown & Margin Analysis
SELECT 
    f.FUEL_NAME,
    f.UNIT,
    f.SELLING_PRICE,
    f.PURCHASE_COST,
    f.PROFIT_PER_UNIT,
    COALESCE(SUM(s.QUANTITY_LITRES), 0) AS TOTAL_LITRES,
    COALESCE(SUM(s.SALES_AMOUNT), 0) AS TOTAL_REVENUE,
    COALESCE(SUM(s.FUEL_COST), 0) AS TOTAL_COST,
    COALESCE(SUM(s.GROSS_PROFIT), 0) AS TOTAL_PROFIT,
    ROUND(COALESCE(SUM(s.GROSS_PROFIT), 0) / NULLIF(SUM(s.SALES_AMOUNT), 0) * 100, 2) AS PROFIT_MARGIN_PCT
FROM FUEL_OPERATIONS.FUEL_TYPES f
LEFT JOIN SALES_MANAGEMENT.FUEL_SALES s ON f.FUEL_TYPE_ID = s.FUEL_TYPE_ID
GROUP BY f.FUEL_TYPE_ID, f.FUEL_NAME, f.UNIT, f.SELLING_PRICE, f.PURCHASE_COST, f.PROFIT_PER_UNIT
ORDER BY TOTAL_REVENUE DESC;

-- 4. Operator Rank by Revenue & Efficiency (Rank & Dense_Rank Window Function)
SELECT 
    s.OPERATOR_ID,
    e.EMPLOYEE_NAME,
    e.ROLE,
    COUNT(s.SALE_ID) AS TRANSACTIONS_HANDLED,
    SUM(s.QUANTITY_LITRES) AS TOTAL_VOLUME,
    SUM(s.SALES_AMOUNT) AS TOTAL_REVENUE,
    SUM(s.GROSS_PROFIT) AS TOTAL_PROFIT,
    RANK() OVER (ORDER BY SUM(s.SALES_AMOUNT) DESC) AS REVENUE_RANK,
    ROUND(SUM(s.SALES_AMOUNT) / NULLIF(COUNT(s.SALE_ID), 0), 2) AS AVG_TICKET_SIZE
FROM SALES_MANAGEMENT.FUEL_SALES s
LEFT JOIN WORKFORCE_ANALYTICS.EMPLOYEES e ON s.OPERATOR_ID = e.EMPLOYEE_ID
GROUP BY s.OPERATOR_ID, e.EMPLOYEE_NAME, e.ROLE
ORDER BY REVENUE_RANK ASC;

-- 5. Inventory Stock Balance and Variance Detection
SELECT 
    i.INVENTORY_ID,
    i.INVENTORY_DATE,
    f.FUEL_NAME,
    i.OPENING_STOCK_LITRES,
    i.RECEIVED_STOCK_LITRES,
    i.RECORDED_SALES_LITRES,
    i.EXPECTED_CLOSING_LITRES,
    i.ACTUAL_CLOSING_LITRES,
    i.VARIANCE_LITRES,
    i.STATUS,
    CASE 
        WHEN i.VARIANCE_LITRES < -30 THEN 'CRITICAL_DISCREPANCY'
        WHEN i.VARIANCE_LITRES < -10 THEN 'WARNING_LOSS'
        ELSE 'ACCEPTABLE_TOLERANCE'
    END AS DISCREPANCY_STATUS
FROM INVENTORY_CONTROL.INVENTORY i
LEFT JOIN FUEL_OPERATIONS.FUEL_TYPES f ON i.FUEL_TYPE_ID = f.FUEL_TYPE_ID
ORDER BY i.INVENTORY_DATE DESC;

-- 6. Net Profit Analysis (Revenue - Fuel Cost - Operating Expenses)
WITH REVENUE_DAILY AS (
    SELECT 
        SALE_DATE,
        SUM(SALES_AMOUNT) AS GROSS_SALES,
        SUM(FUEL_COST) AS COGS,
        SUM(GROSS_PROFIT) AS GROSS_MARGIN
    FROM SALES_MANAGEMENT.FUEL_SALES
    GROUP BY SALE_DATE
),
EXPENSE_DAILY AS (
    SELECT 
        EXPENSE_DATE,
        SUM(AMOUNT) AS OPEX
    FROM INVENTORY_CONTROL.EXPENSES
    GROUP BY EXPENSE_DATE
)
SELECT 
    r.SALE_DATE,
    r.GROSS_SALES,
    r.COGS,
    r.GROSS_MARGIN,
    COALESCE(e.OPEX, 0) AS OPERATING_EXPENSES,
    (r.GROSS_MARGIN - COALESCE(e.OPEX, 0)) AS NET_PROFIT,
    ROUND(((r.GROSS_MARGIN - COALESCE(e.OPEX, 0)) / NULLIF(r.GROSS_SALES, 0)) * 100, 2) AS NET_PROFIT_MARGIN_PCT
FROM REVENUE_DAILY r
LEFT JOIN EXPENSE_DAILY e ON r.SALE_DATE = e.EXPENSE_DATE
ORDER BY r.SALE_DATE DESC;

-- 7. Semi-Structured JSON/VARIANT Extraction
