-- CTE: daily revenue
WITH DAILY_SALES AS (
  SELECT SALE_DATE,SUM(SALES_AMOUNT) AS REVENUE,
         SUM(GROSS_PROFIT) AS GROSS_PROFIT
  FROM SALES_MANAGEMENT.FUEL_SALES
  GROUP BY SALE_DATE
)
SELECT * FROM DAILY_SALES ORDER BY SALE_DATE;

-- Window function: rank operators by revenue
SELECT OPERATOR_ID,
       SUM(SALES_AMOUNT) AS TOTAL_REVENUE,
       RANK() OVER (ORDER BY SUM(SALES_AMOUNT) DESC) AS REVENUE_RANK
FROM SALES_MANAGEMENT.FUEL_SALES
GROUP BY OPERATOR_ID;

-- Subquery: sales above average transaction amount
SELECT SALE_ID,SALE_DATE,SALES_AMOUNT
FROM SALES_MANAGEMENT.FUEL_SALES
WHERE SALES_AMOUNT > (
  SELECT AVG(SALES_AMOUNT) FROM SALES_MANAGEMENT.FUEL_SALES
);

