USE WAREHOUSE SPPA_WH;
USE DATABASE SMART_PETROL_DB;

-- View 1: Fuel Revenue by Fuel Type
CREATE OR REPLACE VIEW SALES_MANAGEMENT.VW_FUEL_REVENUE AS
SELECT f.FUEL_NAME,
       SUM(s.QUANTITY_LITRES) AS LITRES_SOLD,
       SUM(s.SALES_AMOUNT) AS SALES_REVENUE,
       SUM(s.FUEL_COST) AS FUEL_COST,
       SUM(s.GROSS_PROFIT) AS GROSS_PROFIT,
       COUNT(*) AS TRANSACTIONS,
       ROUND(SUM(s.GROSS_PROFIT) / NULLIF(SUM(s.SALES_AMOUNT), 0) * 100, 2) AS MARGIN_PERCENTAGE
FROM SALES_MANAGEMENT.FUEL_SALES s
JOIN FUEL_OPERATIONS.FUEL_TYPES f ON s.FUEL_TYPE_ID=f.FUEL_TYPE_ID
GROUP BY f.FUEL_NAME;

-- View 2: Operator Performance Breakdown
CREATE OR REPLACE VIEW SALES_MANAGEMENT.VW_OPERATOR_PERFORMANCE AS
SELECT s.OPERATOR_ID, e.EMPLOYEE_NAME AS OPERATOR_NAME,
       SUM(s.QUANTITY_LITRES) AS LITRES_SOLD,
       SUM(s.SALES_AMOUNT) AS REVENUE,
       SUM(s.GROSS_PROFIT) AS PROFIT,
       COUNT(*) AS TRANSACTIONS,
       ROUND(SUM(s.SALES_AMOUNT) / NULLIF(COUNT(*), 0), 2) AS AVG_TRANSACTION_VALUE
FROM SALES_MANAGEMENT.FUEL_SALES s
LEFT JOIN WORKFORCE_ANALYTICS.EMPLOYEES e ON s.OPERATOR_ID=e.EMPLOYEE_ID
GROUP BY s.OPERATOR_ID, e.EMPLOYEE_NAME;

-- View 3: Fuel Theft & Inventory Discrepancy Risk Alerts
CREATE OR REPLACE VIEW INVENTORY_CONTROL.VW_FUEL_THEFT_ALERTS AS
SELECT i.INVENTORY_ID,
       i.INVENTORY_DATE,
       f.FUEL_NAME,
       i.OPENING_STOCK_LITRES,
       i.RECEIVED_STOCK_LITRES,
       i.RECORDED_SALES_LITRES,
       i.EXPECTED_CLOSING_LITRES,
       i.ACTUAL_CLOSING_LITRES,
       i.VARIANCE_LITRES,
       ROUND((i.VARIANCE_LITRES / NULLIF(i.EXPECTED_CLOSING_LITRES, 0)) * 100, 2) AS VARIANCE_PERCENTAGE,
       IFF(i.VARIANCE_LITRES < -20, 'HIGH_THEFT_RISK', IFF(i.VARIANCE_LITRES < -5, 'MODERATE_LOSS', 'NORMAL')) AS THEFT_RISK
FROM INVENTORY_CONTROL.INVENTORY i
LEFT JOIN FUEL_OPERATIONS.FUEL_TYPES f ON i.FUEL_TYPE_ID=f.FUEL_TYPE_ID;

-- View 4: Pump Utilization & Efficiency Metrics
CREATE OR REPLACE VIEW FUEL_OPERATIONS.VW_PUMP_UTILIZATION AS
SELECT p.PUMP_ID,
       p.PUMP_NAME,
       p.ISLAND,
       p.STATUS,
       COUNT(s.SALE_ID) AS TOTAL_TRANSACTIONS,
       COALESCE(SUM(s.QUANTITY_LITRES), 0) AS TOTAL_LITRES_DISPENSED,
       COALESCE(SUM(s.SALES_AMOUNT), 0) AS TOTAL_REVENUE,
       COALESCE(SUM(s.GROSS_PROFIT), 0) AS TOTAL_PROFIT
FROM FUEL_OPERATIONS.PUMPS p
LEFT JOIN SALES_MANAGEMENT.FUEL_SALES s ON p.PUMP_ID = s.PUMP_ID
GROUP BY p.PUMP_ID, p.PUMP_NAME, p.ISLAND, p.STATUS;

-- View 5: Customer Loyalty & Segmentation Analytics
CREATE OR REPLACE VIEW CUSTOMER_DATA.VW_CUSTOMER_INSIGHTS AS
SELECT c.CUSTOMER_ID,
       c.CUSTOMER_NAME,
       c.CUSTOMER_TYPE,
       c.FUEL_PREFERENCE,
       c.PAYMENT_METHOD,
       c.CITY,
       COUNT(s.SALE_ID) AS VISIT_COUNT,
       COALESCE(SUM(s.QUANTITY_LITRES), 0) AS LIFETIME_LITRES,
       COALESCE(SUM(s.SALES_AMOUNT), 0) AS LIFETIME_SPEND,
       MAX(s.SALE_DATE) AS LAST_VISIT_DATE
FROM CUSTOMER_DATA.CUSTOMERS c
LEFT JOIN SALES_MANAGEMENT.FUEL_SALES s ON c.CUSTOMER_ID = s.CUSTOMER_ID
GROUP BY c.CUSTOMER_ID, c.CUSTOMER_NAME, c.CUSTOMER_TYPE, c.FUEL_PREFERENCE, c.PAYMENT_METHOD, c.CITY;
